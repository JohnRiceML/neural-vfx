void NvfxSolver::fill_params(Params& p, const NvfxForces* f, float dt) const {
    std::memset(&p, 0, sizeof p);
    p.dt = dt;
    if (f) { p.wind_x = f->wind[0]; p.wind_y = f->wind[1]; p.wind_z = f->wind[2]; }
    p.dx = static_cast<float>(dx);
    p.amb = NVFX_AMBIENT_TEMP;
    p.inv_dx = static_cast<float>(1.0 / dx);
    p.nsub = static_cast<float>(n_diff);
    p.alpha = cfg.buoyancy_alpha; p.beta = cfg.buoyancy_beta; p.eps = cfg.vorticity_eps;
    p.ddiss = cfg.density_dissipation; p.cool = cfg.temperature_cooling; p.burn = cfg.burn_rate;
    p.ign = cfg.ignition_temp; p.bheat = cfg.burn_heat; p.smoke = cfg.smoke_from_fuel;
    p.tol = cfg.pressure_tol; p.maxit = static_cast<float>(cfg.pressure_max_iters);
    p.warm = cfg.pressure_warm_start ? 1.0f : 0.0f;
    p.tmax = cfg.max_temperature; p.wmark = cfg.wind_marker_temp; p.kappa = cfg.heat_diffusion;
    p.cfloor = cfg.confinement_floor;
    if (!f) return;
    p.n_em = static_cast<float>(f->num_emitters);
    for (int i = 0; i < f->num_emitters; ++i) {
        const NvfxEmitter& e = f->emitters[i];
        float* a = p.em[3 * i];
        a[0] = e.pos[0]; a[1] = e.pos[1]; a[2] = e.pos[2]; a[3] = std::max(e.radius, 1e-6f);
        a[4] = e.density_rate; a[5] = e.temperature; a[6] = e.fuel_rate;
        a[8] = e.velocity[0]; a[9] = e.velocity[1]; a[10] = e.velocity[2];
    }
    p.n_imp = static_cast<float>(f->num_impulses);
    for (int i = 0; i < f->num_impulses; ++i) {
        const NvfxImpulse& m = f->impulses[i];
        float* a = p.imp[2 * i];
        a[0] = m.pos[0]; a[1] = m.pos[1]; a[2] = m.pos[2]; a[3] = std::max(m.radius, 1e-6f);
        a[4] = m.velocity[0]; a[5] = m.velocity[1]; a[6] = m.velocity[2];
    }
}

bool NvfxSolver::wait_slot(uint64_t c) {
    if (c <= kRing) return true;
    uint64_t prev = c - kRing;
    auto* rb = reinterpret_cast<volatile RbSlot*>(static_cast<uint8_t*>(readback.map) + ((prev - 1) % kRb) * kRbSlot);
    if (rb->tag == uint32_t(prev)) return true;
    if (!ctx->hosted) {
        // our own submissions: the fence covers it
        if (!ctx->wait(ctx->fence_next - 1)) return false;
        if (rb->tag == uint32_t(prev)) return true;
    }
    for (int i = 0; i < 20000; ++i) {   // hosted: the host executes our lists; poll the marker
        Sleep(1);
        if (rb->tag == uint32_t(prev)) return true;
    }
    set_error("ring slot of step %llu never completed (host did not execute the recorded list?)",
              static_cast<unsigned long long>(prev));
    return false;
}

bool NvfxSolver::ensure_preds(int k) {
    for (int i = npred + 1; i <= k; ++i) {
        if (!ctx->create_buffer(pred[i], 256, D3D12_HEAP_TYPE_DEFAULT, true, "pred")) return false;
        D3D12_UNORDERED_ACCESS_VIEW_DESC u = {};
        u.Format = DXGI_FORMAT_R32_TYPELESS;
        u.ViewDimension = D3D12_UAV_DIMENSION_BUFFER;
        u.Buffer.NumElements = 64;
        u.Buffer.Flags = D3D12_BUFFER_UAV_FLAG_RAW;
        ctx->device->CreateUnorderedAccessView(pred[i].res.Get(), nullptr, &u, cpu(SL_PRED0 + i));
        npred = i;
    }
    return true;
}

bool NvfxSolver::init() {
    ID3D12Device* dev = ctx->device.Get();
    dx = 1.0 / N;
    n_diff = std::max(1, (N + 255) / 256);
    uint64_t n3 = uint64_t(N) * N * N;
    nb = cdiv(n3, 512);
    nbm = cdiv(N, 8) * cdiv(N, 8) * cdiv(N, 4);

    // root signature: b0 = 16 constants, b1 = root CBV, heap directly indexed
    D3D12_ROOT_PARAMETER1 rp[2] = {};
    rp[0].ParameterType = D3D12_ROOT_PARAMETER_TYPE_32BIT_CONSTANTS;
    rp[0].Constants = {0, 0, 16};
    rp[0].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    rp[1].ParameterType = D3D12_ROOT_PARAMETER_TYPE_CBV;
    rp[1].Descriptor = {1, 0, D3D12_ROOT_DESCRIPTOR_FLAG_DATA_VOLATILE};
    rp[1].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    D3D12_VERSIONED_ROOT_SIGNATURE_DESC rsd = {};
    rsd.Version = D3D_ROOT_SIGNATURE_VERSION_1_1;
    rsd.Desc_1_1.NumParameters = 2;
    rsd.Desc_1_1.pParameters = rp;
    rsd.Desc_1_1.Flags = D3D12_ROOT_SIGNATURE_FLAG_CBV_SRV_UAV_HEAP_DIRECTLY_INDEXED;
    ComPtr<ID3DBlob> blob, err;
    if (FAILED(D3D12SerializeVersionedRootSignature(&rsd, &blob, &err))) {
        set_error("root signature: %s", err ? static_cast<const char*>(err->GetBufferPointer()) : "?");
        return false;
    }
    if (!ok(dev->CreateRootSignature(0, blob->GetBufferPointer(), blob->GetBufferSize(), IID_PPV_ARGS(&rs)), "CreateRootSignature"))
        return false;
    for (int p = 0; p < PSO_COUNT; ++p) {
        const ShaderEntry* e = nullptr;
        for (const auto& t : kShaderTable)
            if (std::strcmp(t.name, kPsoNames[p]) == 0) e = &t;
        if (!e) { set_error("internal: shader %s not embedded", kPsoNames[p]); return false; }
        D3D12_COMPUTE_PIPELINE_STATE_DESC d = {};
        d.pRootSignature = rs.Get();
        d.CS = {e->data, e->size};
        if (!ok(dev->CreateComputePipelineState(&d, IID_PPV_ARGS(&pso[p])), kPsoNames[p])) return false;
    }

    // descriptor heap
    D3D12_DESCRIPTOR_HEAP_DESC hd = {D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV, SL_COUNT, D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE};
    if (!ok(dev->CreateDescriptorHeap(&hd, IID_PPV_ARGS(&heap)), "CreateDescriptorHeap")) return false;
    inc = dev->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);

    auto srv3d = [&](ID3D12Resource* r, DXGI_FORMAT f, int slot) {
        D3D12_SHADER_RESOURCE_VIEW_DESC d = {};
        d.Format = f;
        d.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE3D;
        d.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
        d.Texture3D.MipLevels = 1;
        dev->CreateShaderResourceView(r, &d, cpu(slot));
    };
    auto uav3d = [&](ID3D12Resource* r, DXGI_FORMAT f, int slot) {
        D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
        d.Format = f;
        d.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE3D;
        d.Texture3D.WSize = UINT(N);
        dev->CreateUnorderedAccessView(r, nullptr, &d, cpu(slot));
    };
    const DXGI_FORMAT F4 = DXGI_FORMAT_R32G32B32A32_FLOAT, F2 = DXGI_FORMAT_R32G32_FLOAT, F1 = DXGI_FORMAT_R32_FLOAT;
    for (int i = 0; i < 2; ++i) {
        if (!ctx->create_tex3d(vd[i], F4, N, NPSR, i ? "vel_density1" : "vel_density0")) return false;
        if (!ctx->create_tex3d(tf[i], F2, N, NPSR, i ? "temp_fuel1" : "temp_fuel0")) return false;
        srv3d(vd[i].Get(), F4, SL_VD_SRV0 + i);
        srv3d(tf[i].Get(), F2, SL_TF_SRV0 + i);
        uav3d(vd[i].Get(), F4, SL_VD_UAV0 + i);
        uav3d(tf[i].Get(), F2, SL_TF_UAV0 + i);
    }
    if (!ctx->create_tex3d(solid, F1, N, NPSR, "solid")) return false;
    srv3d(solid.Get(), F1, SL_SOLID_SRV);
    struct { ComPtr<ID3D12Resource>* r; DXGI_FORMAT f; int slot; const char* name; } tex[] = {
        {&hat_vd, F4, SL_HAT_VD, "hat_vd"}, {&hat_tf, F2, SL_HAT_TF, "hat_tf"}, {&adv_vd, F4, SL_ADV_VD, "adv_vd"},
        {&adv_tf, F2, SL_ADV_TF, "adv_tf"}, {&omega, F4, SL_OMEGA, "omega"}, {&omega_s, F4, SL_OMEGA_S, "omega_s"},
        {&force, F4, SL_FORCE, "force"}, {&ta, F4, SL_TA, "ta"}, {&tb, F4, SL_TB, "tb"}};
    for (auto& t : tex) {
        if (!ctx->create_tex3d(*t.r, t.f, N, UAV, t.name)) return false;
        uav3d(t.r->Get(), t.f, t.slot);
    }

    auto sbuf = [&](Buffer& b, uint64_t count, int slot, const char* name) {
        if (!ctx->create_buffer(b, count * 4, D3D12_HEAP_TYPE_DEFAULT, true, name)) return false;
        D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
        d.Format = DXGI_FORMAT_UNKNOWN;
        d.ViewDimension = D3D12_UAV_DIMENSION_BUFFER;
        d.Buffer.NumElements = UINT(count);
        d.Buffer.StructureByteStride = 4;
        dev->CreateUnorderedAccessView(b.res.Get(), nullptr, &d, cpu(slot));
        return true;
    };
    struct { Buffer* b; uint64_t count; int slot; const char* name; } bufs[] = {
        {&fm, n3, SL_FM, "fm"}, {&pr, n3, SL_PR, "r"}, {&pz, n3, SL_PZ, "z"}, {&pp, n3, SL_PP, "p"},
        {&pq, n3, SL_PQ, "q"}, {&phi, n3, SL_PHI, "phi"}, {&z0, n3, SL_Z0, "z0"}, {&rr, n3, SL_RR, "rr"},
        {&zt, n3, SL_ZT, "zt"}, {&part, 2ull * nb, SL_PART, "part"}, {&part_pq, 2ull * nb, SL_PART_PQ, "part_pq"},
        {&mpart, 2ull * nbm, SL_MPART, "mass_part"}, {&pp2, n3, SL_PP2, "p2"}};
    for (auto& b : bufs)
        if (!sbuf(*b.b, b.count, b.slot, b.name)) return false;
    {
        if (!ctx->create_buffer(scal, S_WORDS * 4, D3D12_HEAP_TYPE_DEFAULT, true, "scal")) return false;
        D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
        d.Format = DXGI_FORMAT_R32_TYPELESS;
        d.ViewDimension = D3D12_UAV_DIMENSION_BUFFER;
        d.Buffer.NumElements = S_WORDS;
        d.Buffer.Flags = D3D12_BUFFER_UAV_FLAG_RAW;
        dev->CreateUnorderedAccessView(scal.res.Get(), nullptr, &d, cpu(SL_SCAL));
    }

    // multigrid levels (pressure.py PressureSolver3D.__init__)
    uint32_t ox = 0, oo = 0;
    int m = N / 2, level = 1;
    while (true) {
        Level L = {};
        L.m = uint32_t(m);
        L.ox = L.orr = L.od = ox;
        L.oo = oo;
        L.dmin = static_cast<float>(kDminRel * 6.0 * std::pow(0.25, level - 1));
        lv.push_back(L);
        ox += 8u * m * m * m;
        oo += 24u * m * m * m;
        if (m % 2 == 1 || m == 1) break;
        m /= 2;
        ++level;
    }
    fused = env_int("NVFX_SIM_FUSED", 1) != 0;
    block_m = fused ? 8 : kBlockMPython;
    if (fused) block_m = std::clamp(env_int("NVFX_SIM_BLOCK_M", block_m), 1, 8);
    block_level = static_cast<int>(lv.size()) - 1;
    for (size_t i = 0; i < lv.size(); ++i)
        if (lv[i].m <= uint32_t(block_m)) { block_level = static_cast<int>(i); break; }
    fast = !(lv.size() - block_level > 4 || lv[block_level].m > uint32_t(block_m) || block_level == 0);
    if (!sbuf(lx, ox, SL_LX, "mg_x") || !sbuf(lr, ox, SL_LR, "mg_r") || !sbuf(ld, ox, SL_LD, "mg_diag") ||
        !sbuf(lo, oo, SL_LO, "mg_off"))
        return false;
    if (!ctx->create_buffer(levels, lv.size() * sizeof(Level), D3D12_HEAP_TYPE_DEFAULT, false, "levels")) return false;
    {
        D3D12_SHADER_RESOURCE_VIEW_DESC d = {};
        d.Format = DXGI_FORMAT_UNKNOWN;
        d.ViewDimension = D3D12_SRV_DIMENSION_BUFFER;
        d.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
        d.Buffer.NumElements = UINT(lv.size());
        d.Buffer.StructureByteStride = sizeof(Level);
        dev->CreateShaderResourceView(levels.res.Get(), &d, cpu(SL_LEVELS));
    }

    prof.on = env_int("NVFX_SIM_PROFILE", 0) != 0;
    if (prof.on) {
        D3D12_QUERY_HEAP_DESC pd = {D3D12_QUERY_HEAP_TYPE_TIMESTAMP, 16384, 0};
        if (!ok(dev->CreateQueryHeap(&pd, IID_PPV_ARGS(&prof.heap)), "CreateQueryHeap")) return false;
        if (!ctx->create_buffer(prof.rb, 16384 * 8, D3D12_HEAP_TYPE_READBACK, false, "prof_rb")) return false;
    }
    if (!ctx->create_buffer(params, kParamSlot, D3D12_HEAP_TYPE_DEFAULT, false, "params")) return false;
    if (!ctx->create_buffer(upload, uint64_t(kRing) * kParamSlot, D3D12_HEAP_TYPE_UPLOAD, false, "param_ring")) return false;
    if (!ctx->create_buffer(readback, uint64_t(kRb) * kRbSlot, D3D12_HEAP_TYPE_READBACK, false, "readback")) return false;
    std::memset(readback.map, 0, size_t(kRb) * kRbSlot);
    D3D12_QUERY_HEAP_DESC qd = {D3D12_QUERY_HEAP_TYPE_TIMESTAMP, kRb * 4, 0};
    if (!ok(dev->CreateQueryHeap(&qd, IID_PPV_ARGS(&qheap)), "CreateQueryHeap")) return false;
    uint64_t rp_solid = uint64_t((N * 4 + 255) & ~255) * N * N;
    if (!ctx->create_buffer(solid_staging, rp_solid, D3D12_HEAP_TYPE_UPLOAD, false, "solid_staging")) return false;
    if (!ensure_preds(cfg.pressure_max_iters)) return false;

    // upload the level table
    Buffer up;
    if (!ctx->create_buffer(up, lv.size() * sizeof(Level), D3D12_HEAP_TYPE_UPLOAD, false, "levels_up")) return false;
    std::memcpy(up.map, lv.data(), lv.size() * sizeof(Level));
    ID3D12GraphicsCommandList2* l = ctx->begin();
    if (!l) return false;
    l->CopyBufferRegion(levels.res.Get(), 0, up.res.Get(), 0, lv.size() * sizeof(Level));
    uint64_t v = ctx->submit();
    return v && ctx->wait(v);
}

