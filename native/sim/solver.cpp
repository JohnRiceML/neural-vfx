enum Pso {
    ADV_SL, ADV_MC, MASS_FIN,
    SOURCES, DIFFUSE, CURL, SEP_X, SEP_Y, SEP_Z_STORE, SEP_Z_APPLY, BODY_FORCES,
    P_RHS, P_FIN_MAXU, P_MATVEC_DOT, P_PRE, P_RESID, P_POST_RZ, P_FIN_RZ, P_UPD_P, P_APPLY,
    P_FWD_RED, P_SMOOTH_H, P_RESTRICT_RED, P_PROLONG_BLACK, P_INV_TRANSFORM, P_COARSE_BLOCK,
    P_SMOOTH, P_PROLONG, P_COARSEST,
    S_INIT, S_MASK, S_PROBE1, S_GALERKIN,
    P_CG_UPDATE, P_COARSE_LDS, P_RESID_FWD,
    PSO_COUNT
};
