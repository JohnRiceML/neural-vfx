// Native port of vfx/sim3d Solver3D (D3D12 compute, HLSL). Same stages, same order, same constants.
//
// Recording model: one command list per step, one shader-visible descriptor heap bound once,
// one root signature (16 root constants + one root CBV), every resource reached through
// ResourceDescriptorHeap[SL_*]. Global UAV barriers only between dependent dispatches.
// The PCG loop records pressure_max_iters iterations; iteration k is wrapped in SetPredication on a
// per-iteration predicate buffer that the previous iteration's p_fin_rz writes (GPU-side stop,
// no host sync). Timestamps / iteration count go to a readback ring tagged with a
// WriteBufferImmediate marker, read without blocking.
