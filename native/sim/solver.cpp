struct Params {   // mirrors struct Params in shaders/common.hlsli
    float dt, wind_x, wind_y, wind_z;
    float n_em, n_imp, dx, amb;
    float kappa, cfloor, warm, inv_dx;
    float alpha, beta, eps, ddiss;
    float cool, burn, ign, bheat;
    float smoke, tol, maxit, tmax;
    float wmark, nsub, pad0, pad1;
    float em[96][4];
    float imp[64][4];
};
static_assert(sizeof(Params) == 112 + 160 * 16, "Params layout");

struct Level {    // mirrors struct Level in common.hlsli
    uint32_t m, ox, orr, od, oo, pad0, pad1, pad2;
    float dmin, f1, f2, f3;
};
static_assert(sizeof(Level) == 48, "Level layout");

constexpr int kRing = 16;              // param upload slots (max steps in flight)
constexpr int kRb = 64;                // timestamp / readback slots (> kRing: a slot is never rewritten while it can be read)
constexpr uint32_t kParamSlot = 4096;  // >= sizeof(Params), 256-aligned
constexpr uint32_t kRbSlot = 64;       // readback: 4 x u64 timestamps, it, kind, tag, step lo, step hi
enum Kind : uint32_t { KIND_STEP = 1, KIND_PROJECT = 2 };

constexpr double kGalerkinScale = 1.0 / 16.0;
constexpr double kDminRel = 1.0e-3;
constexpr int kBlockMPython = 2;   // pressure.py BLOCK_M (single-group bottom from m <= 2)

int env_int(const char* name, int fallback) {
    char* v = nullptr;
    size_t len = 0;
    if (_dupenv_s(&v, &len, name) != 0 || !v) return fallback;
    int r = std::atoi(v);
    std::free(v);
    return r;
}

uint32_t cdiv(uint64_t a, uint64_t b) { return static_cast<uint32_t>((a + b - 1) / b); }

D3D12_RESOURCE_BARRIER transition(ID3D12Resource* r, D3D12_RESOURCE_STATES a, D3D12_RESOURCE_STATES b) {
    D3D12_RESOURCE_BARRIER x = {};
    x.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
    x.Transition.pResource = r;
    x.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
    x.Transition.StateBefore = a;
    x.Transition.StateAfter = b;
    return x;
}
D3D12_RESOURCE_BARRIER uav_barrier() {
    D3D12_RESOURCE_BARRIER x = {};
    x.Type = D3D12_RESOURCE_BARRIER_TYPE_UAV;
    x.UAV.pResource = nullptr;
    return x;
}

constexpr D3D12_RESOURCE_STATES NPSR = D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE;
constexpr D3D12_RESOURCE_STATES UAV = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;

