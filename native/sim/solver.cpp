// ------------------------------------------------------------------ recording helper
struct Rec {
    NvfxSolver* s;
    ID3D12GraphicsCommandList2* l;
    ID3D12PipelineState* bound = nullptr;
    std::vector<D3D12_RESOURCE_BARRIER> pending;

    void begin() {
        ID3D12DescriptorHeap* h = s->heap.Get();
        l->SetDescriptorHeaps(1, &h);
        l->SetComputeRootSignature(s->rs.Get());
        l->SetComputeRoot32BitConstant(0, static_cast<UINT>(s->N), 15);
        l->SetComputeRootConstantBufferView(1, s->params.va());
    }
    uint32_t k0 = 0;
    int last = -1;
    bool prof = false;
    void k(std::initializer_list<uint32_t> v) {
        l->SetComputeRoot32BitConstants(0, static_cast<UINT>(v.size()), v.begin(), 0);
        k0 = *v.begin();
    }
    void go(Pso p, uint32_t gx, uint32_t gy = 1, uint32_t gz = 1) {
        ID3D12PipelineState* ps = s->pso[p].Get();
        if (ps != bound) { l->SetPipelineState(ps); bound = ps; }
        l->Dispatch(gx, gy, gz);
        last = p;
    }
    void prof_mark(const std::string& label) {
        if (!prof) return;
        l->EndQuery(s->prof.heap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, UINT(s->prof.labels.size()));
        s->prof.labels.push_back(label);
    }
    void grid(Pso p) { go(p, cdiv(s->N, 8), cdiv(s->N, 8), cdiv(s->N, 4)); }
    void items(Pso p, uint64_t n, uint32_t tg) { go(p, cdiv(n, tg)); }
    void flat(Pso p) { go(p, s->nb); }
    // barrier batch: a UAV barrier plus any queued transitions
    void tr(ID3D12Resource* r, D3D12_RESOURCE_STATES a, D3D12_RESOURCE_STATES b) { pending.push_back(transition(r, a, b)); }
    void sync(bool with_uav = true) {
        if (with_uav) pending.push_back(uav_barrier());
        if (!pending.empty()) l->ResourceBarrier(static_cast<UINT>(pending.size()), pending.data());
        pending.clear();
        if (prof && last >= 0) {
            bool lvl = last == P_SMOOTH_H || last == P_RESTRICT_RED || last == P_PROLONG_BLACK || last == P_SMOOTH ||
                       last == P_PROLONG || last == S_GALERKIN;
            prof_mark(std::string(kPsoNames[last]) + (lvl ? "#" + std::to_string(k0) : std::string()));
        }
        last = -1;
    }
};

uint32_t asu(float f) { uint32_t u; std::memcpy(&u, &f, 4); return u; }

// ------------------------------------------------------------------ pressure recording
void rec_vcycle(Rec& r, int init, int j) {
    NvfxSolver* s = r.s;
    const auto& L = s->lv;
    auto half_items = [&](int l) { uint64_t m = L[l].m; return 8 * m * m * (m / 2); };
    auto full_items = [&](int l) { uint64_t m = L[l].m; return 8 * m * m * m; };
    uint64_t n3 = static_cast<uint64_t>(s->N) * s->N * s->N;
    // fused path: the CG scalars / p.q partials of iteration j-1 are in bank (j-1)&1
    r.k({static_cast<uint32_t>(init), s->fused ? uint32_t((j - 1) & 1) : 0xFFFFFFFFu}); r.flat(P_PRE); r.sync();
    if (!(s->fused && s->fast)) { r.flat(P_RESID); r.sync(); }
    if (s->fast) {
        int S = s->block_level;
        r.k({1}); r.items(s->fused ? P_RESID_FWD : P_FWD_RED, uint64_t(L[0].m) * L[0].m * L[0].m, 64); r.sync();
        for (int l = 0; l < S; ++l) {
            r.k({uint32_t(l), 1}); r.items(P_SMOOTH_H, half_items(l), 64); r.sync();
            r.k({uint32_t(l), l + 1 == S ? 0u : 1u}); r.items(P_RESTRICT_RED, full_items(l + 1), 64); r.sync();
        }
        r.k({uint32_t(S), uint32_t(L.size() - S)}); r.go(s->fused ? P_COARSE_LDS : P_COARSE_BLOCK, 1); r.sync();
        for (int l = S - 1; l >= 0; --l) {
            r.k({uint32_t(l)}); r.items(P_PROLONG_BLACK, half_items(l), 64); r.sync();
            r.k({uint32_t(l), 0}); r.items(P_SMOOTH_H, half_items(l), 64); r.sync();
        }
    } else {
        int nl = static_cast<int>(L.size());
        r.k({0}); r.items(P_FWD_RED, uint64_t(L[0].m) * L[0].m * L[0].m, 64); r.sync();
        for (int l = 0; l < nl - 1; ++l) {
            r.k({uint32_t(l), 0, 1}); r.items(P_SMOOTH, full_items(l), 64); r.sync();
            r.k({uint32_t(l), 1, 0}); r.items(P_SMOOTH, full_items(l), 64); r.sync();
            r.k({uint32_t(l), 0}); r.items(P_RESTRICT_RED, full_items(l + 1), 64); r.sync();
        }
        int c = nl - 1;
        if (L[c].m == 1) {
            r.k({uint32_t(c)}); r.go(P_COARSEST, 1); r.sync();
        } else {
            for (uint32_t k = 0; k < 2 * L[c].m; ++k) {
                r.k({uint32_t(c), 0, k == 0 ? 1u : 0u}); r.items(P_SMOOTH, full_items(c), 64); r.sync();
                r.k({uint32_t(c), 1, 0}); r.items(P_SMOOTH, full_items(c), 64); r.sync();
            }
        }
        for (int l = nl - 2; l >= 0; --l) {
            r.k({uint32_t(l)}); r.items(P_PROLONG, full_items(l), 64); r.sync();
            r.k({uint32_t(l), 1, 0}); r.items(P_SMOOTH, full_items(l), 64); r.sync();
            r.k({uint32_t(l), 0, 0}); r.items(P_SMOOTH, full_items(l), 64); r.sync();
        }
    }
    r.items(P_INV_TRANSFORM, n3, 256); r.sync();
    r.flat(P_POST_RZ); r.sync();
}

// Projects the velocity in texture slot vd_uav (must be in UAV state). Preds 1..maxit must be in
// UAV state on entry; they are left in PREDICATION state.
void rec_projection(Rec& r, uint32_t vd_uav, int maxit) {
    NvfxSolver* s = r.s;
    uint64_t n3 = static_cast<uint64_t>(s->N) * s->N * s->N;
    r.k({vd_uav}); r.flat(P_RHS); r.sync();
    r.k({uint32_t(maxit)}); r.go(P_FIN_MAXU, 1); r.sync();
    const uint32_t PP[2] = {SL_PP, SL_PP2};
    rec_vcycle(r, 1, 0);
    if (s->fused) {
        r.k({1, maxit >= 1 ? uint32_t(SL_PRED0 + 1) : 0u, PP[1], PP[0], 1, 0}); r.flat(P_CG_UPDATE);
        if (maxit >= 1) r.tr(s->pred[1].res.Get(), UAV, D3D12_RESOURCE_STATE_PREDICATION);
        r.sync();
    } else {
        r.k({1, maxit >= 1 ? uint32_t(SL_PRED0 + 1) : 0u}); r.go(P_FIN_RZ, 1);
        if (maxit >= 1) r.tr(s->pred[1].res.Get(), UAV, D3D12_RESOURCE_STATE_PREDICATION);
        r.sync();
        r.k({1}); r.flat(P_UPD_P); r.sync();
    }
    for (int it = 1; it <= maxit; ++it) {
        r.l->SetPredication(s->pred[it].res.Get(), 0, D3D12_PREDICATION_OP_EQUAL_ZERO);
        uint32_t next_pred = it < maxit ? uint32_t(SL_PRED0 + it + 1) : 0u;
        if (s->fused) {
            rec_vcycle(r, 0, it);
            r.k({0, next_pred, PP[(it - 1) & 1], PP[it & 1], uint32_t((it - 1) & 1), uint32_t(it & 1)});
            r.flat(P_CG_UPDATE);
            if (it < maxit) r.tr(s->pred[it + 1].res.Get(), UAV, D3D12_RESOURCE_STATE_PREDICATION);
            r.sync();
        } else {
            r.flat(P_MATVEC_DOT); r.sync();
            rec_vcycle(r, 0, it);
            r.k({0, next_pred}); r.go(P_FIN_RZ, 1);
            if (it < maxit) r.tr(s->pred[it + 1].res.Get(), UAV, D3D12_RESOURCE_STATE_PREDICATION);
            r.sync();
            r.k({0}); r.flat(P_UPD_P); r.sync();
        }
    }
    if (maxit >= 1) r.l->SetPredication(nullptr, 0, D3D12_PREDICATION_OP_EQUAL_ZERO);
    r.k({vd_uav}); r.items(P_APPLY, n3, 256); r.sync();
}

void rec_setup_ops(Rec& r) {
    NvfxSolver* s = r.s;
    r.grid(S_MASK); r.sync();
    uint64_t m0 = s->lv[0].m;
    r.items(S_PROBE1, 8 * m0 * m0 * m0, 64); r.sync();
    for (size_t l = 0; l + 1 < s->lv.size(); ++l) {
        uint64_t mb = s->lv[l + 1].m;
        r.k({uint32_t(l), asu(static_cast<float>(kGalerkinScale))});
        r.items(S_GALERKIN, 8 * mb * mb * mb, 64);
        r.sync();
    }
}

// ring slot bookkeeping in the readback buffer
struct RbSlot { uint64_t ts[4]; uint32_t it, kind, tag, step_lo, step_hi, pad[3]; };
static_assert(sizeof(RbSlot) == kRbSlot, "RbSlot");

void rec_tail(Rec& r, uint64_t c, uint32_t kind) {
    NvfxSolver* s = r.s;
    uint32_t slot = static_cast<uint32_t>((c - 1) % kRb);
    D3D12_GPU_VIRTUAL_ADDRESS base = s->readback.va() + uint64_t(slot) * kRbSlot;
    if (kind == KIND_STEP)
        r.l->ResolveQueryData(s->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, slot * 4, 4, s->readback.res.Get(),
                              uint64_t(slot) * kRbSlot);
    r.l->CopyBufferRegion(s->readback.res.Get(), uint64_t(slot) * kRbSlot + 32, s->scal.res.Get(), 4 * S_IT, 4);
    r.tr(s->scal.res.Get(), D3D12_RESOURCE_STATE_COPY_SOURCE, D3D12_RESOURCE_STATE_COMMON);
    r.sync(false);
    D3D12_WRITEBUFFERIMMEDIATE_PARAMETER wp[4] = {
        {base + 36, kind}, {base + 44, uint32_t(s->step_no)}, {base + 48, uint32_t(s->step_no >> 32)},
        {base + 40, uint32_t(c)}};
    D3D12_WRITEBUFFERIMMEDIATE_MODE wm[4] = {D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT, D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT,
                                             D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT, D3D12_WRITEBUFFERIMMEDIATE_MODE_MARKER_OUT};
    r.l->WriteBufferImmediate(4, wp, wm);
}

// common prologue of step / project: param upload, state transitions of the scratch buffers
void rec_head(Rec& r, int maxit) {
    NvfxSolver* s = r.s;
    r.begin();
    r.tr(s->params.res.Get(), D3D12_RESOURCE_STATE_COMMON, D3D12_RESOURCE_STATE_COPY_DEST);
    r.tr(s->scal.res.Get(), D3D12_RESOURCE_STATE_COMMON, UAV);
    for (int k = 1; k <= maxit; ++k) r.tr(s->pred[k].res.Get(), D3D12_RESOURCE_STATE_COMMON, UAV);
}

void rec_head2(Rec& r, uint64_t c) {
    NvfxSolver* s = r.s;
    uint32_t slot = static_cast<uint32_t>((c - 1) % kRing);
    r.l->CopyBufferRegion(s->params.res.Get(), 0, s->upload.res.Get(), uint64_t(slot) * kParamSlot, sizeof(Params));
    r.tr(s->params.res.Get(), D3D12_RESOURCE_STATE_COPY_DEST, D3D12_RESOURCE_STATE_VERTEX_AND_CONSTANT_BUFFER);
}

void rec_end_common(Rec& r, int maxit) {
    NvfxSolver* s = r.s;
    r.tr(s->params.res.Get(), D3D12_RESOURCE_STATE_VERTEX_AND_CONSTANT_BUFFER, D3D12_RESOURCE_STATE_COMMON);
    r.tr(s->scal.res.Get(), UAV, D3D12_RESOURCE_STATE_COPY_SOURCE);
    for (int k = 1; k <= maxit; ++k) r.tr(s->pred[k].res.Get(), D3D12_RESOURCE_STATE_PREDICATION, D3D12_RESOURCE_STATE_COMMON);
}

NvfxResult record_step(NvfxSolver* s, ID3D12GraphicsCommandList2* l, const NvfxForces* f, float dt) {
    int maxit = s->cfg.pressure_max_iters;
    if (!s->ensure_preds(maxit)) return NVFX_ERR_DEVICE;
    uint64_t c = s->counter + 1;
    if (!s->wait_slot(c)) return NVFX_ERR_DEVICE;
    s->counter = c;
    uint32_t slot = static_cast<uint32_t>((c - 1) % kRing);
    s->fill_params(*reinterpret_cast<Params*>(static_cast<uint8_t*>(s->upload.map) + uint64_t(slot) * kParamSlot), f, dt);
    s->step_no += 1;
    uint32_t qs = static_cast<uint32_t>((c - 1) % kRb);

    int cur = s->cur, nxt = 1 - s->cur;
    Rec r{s, l};
    rec_head(r, maxit);
    r.tr(s->vd[nxt].Get(), NPSR, UAV);
    r.tr(s->tf[nxt].Get(), NPSR, UAV);
    r.sync(false);
    rec_head2(r, c);
    r.sync(false);
    l->EndQuery(s->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * 4 + 0);
    if (s->prof.on) {
        r.prof = true;
        s->prof.labels.clear();
        r.prof_mark("start");
    }

    // 1-2. advection (all channels) + mass correction reduction
    r.k({uint32_t(cur)}); r.grid(ADV_SL); r.sync();
    r.k({uint32_t(cur), s->nbm}); r.grid(ADV_MC); r.sync();
    r.k({0, s->nbm}); r.go(MASS_FIN, 1); r.sync();
    l->EndQuery(s->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * 4 + 1);

    // 3. sources, heat + fuel diffusion (ping-pong ends in the next state set)
    uint32_t nvd = SL_VD_UAV0 + nxt, ntf = SL_TF_UAV0 + nxt;
    uint32_t bvd[2], btf[2];
    if (s->n_diff % 2 == 0) { bvd[0] = nvd; btf[0] = ntf; bvd[1] = SL_HAT_VD; btf[1] = SL_HAT_TF; }
    else { bvd[0] = SL_HAT_VD; btf[0] = SL_HAT_TF; bvd[1] = nvd; btf[1] = ntf; }
    r.k({bvd[0], btf[0]}); r.grid(SOURCES); r.sync();
    for (int k = 0; k < s->n_diff; ++k) {
        r.k({bvd[k % 2], btf[k % 2], bvd[(k + 1) % 2], btf[(k + 1) % 2]}); r.grid(DIFFUSE); r.sync();
    }
    // 4. vorticity confinement, buoyancy, wind; smoothed force
    r.k({nvd}); r.grid(CURL); r.sync();
    r.k({SL_OMEGA}); r.grid(SEP_X); r.sync();
    r.grid(SEP_Y); r.sync();
    r.grid(SEP_Z_STORE); r.sync();
    r.k({nvd, ntf}); r.grid(BODY_FORCES); r.sync();
    r.k({SL_FORCE}); r.grid(SEP_X); r.sync();
    r.grid(SEP_Y); r.sync();
    r.k({nvd}); r.grid(SEP_Z_APPLY); r.sync();
    l->EndQuery(s->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * 4 + 2);

    // 5. projection
    rec_projection(r, nvd, maxit);
    l->EndQuery(s->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * 4 + 3);

    r.tr(s->vd[nxt].Get(), UAV, NPSR);
    r.tr(s->tf[nxt].Get(), UAV, NPSR);
    rec_end_common(r, maxit);
    r.sync(false);
    if (r.prof)
        l->ResolveQueryData(s->prof.heap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 0, UINT(s->prof.labels.size()), s->prof.rb.res.Get(), 0);
    rec_tail(r, c, KIND_STEP);
    s->cur = nxt;
    return NVFX_OK;
}

bool check_forces(const NvfxForces* f) {
    if (!f) return true;
    if (f->num_emitters < 0 || f->num_emitters > NVFX_MAX_EMITTERS || (f->num_emitters > 0 && !f->emitters)) {
        set_error("num_emitters must be 0..%d with a non-NULL array", NVFX_MAX_EMITTERS);
        return false;
    }
    if (f->num_impulses < 0 || f->num_impulses > NVFX_MAX_IMPULSES || (f->num_impulses > 0 && !f->impulses)) {
        set_error("num_impulses must be 0..%d with a non-NULL array", NVFX_MAX_IMPULSES);
        return false;
    }
    return true;
}

bool check_config(const NvfxSolverConfig* c) {
    if (c->pressure_max_iters < 0 || c->pressure_max_iters > NVFX_MAX_PRED) {
        set_error("pressure_max_iters must be 0..%d", NVFX_MAX_PRED);
        return false;
    }
    return true;
}

// float32 rasterization with the same operations as torch in rasterize_obstacles_3d
void rasterize(const NvfxObstacle* obs, int n_obs, int N, std::vector<float>& solid) {
    solid.assign(size_t(N) * N * N, 0.0f);
    const float dx = static_cast<float>(1.0 / N);
    std::vector<float> c(N);
    for (int i = 0; i < N; ++i) c[i] = (static_cast<float>(i) + 0.5f) * dx;
    for (int k = 0; k < n_obs; ++k) {
        const NvfxObstacle& o = obs[k];
        float r2 = static_cast<float>(double(o.size[0]) * double(o.size[0]));
        for (int z = 0; z < N; ++z)
            for (int y = 0; y < N; ++y)
                for (int x = 0; x < N; ++x) {
                    bool in;
                    if (o.kind == NVFX_OBSTACLE_SPHERE) {
                        float a = c[x] - o.pos[0], b = c[y] - o.pos[1], d = c[z] - o.pos[2];
                        float aa = a * a, bb = b * b, dd = d * d;
                        float sum = aa + bb;
                        sum = sum + dd;
                        in = sum <= r2;
                    } else {
                        in = std::fabs(c[x] - o.pos[0]) <= o.size[0] && std::fabs(c[y] - o.pos[1]) <= o.size[1] &&
                             std::fabs(c[z] - o.pos[2]) <= o.size[2];
                    }
                    if (in) solid[(size_t(z) * N + y) * N + x] = 1.0f;
                }
    }
}

