struct NvfxSolver {
    NvfxContext* ctx = nullptr;
    int N = 0;
    NvfxSolverConfig cfg = {};
    double dx = 0.0;
    int n_diff = 1;
    uint32_t nb = 0, nbm = 0;

    ComPtr<ID3D12RootSignature> rs;
    ComPtr<ID3D12PipelineState> pso[PSO_COUNT];
    ComPtr<ID3D12DescriptorHeap> heap;
    UINT inc = 0;

    ComPtr<ID3D12Resource> vd[2], tf[2], solid;
    ComPtr<ID3D12Resource> hat_vd, hat_tf, adv_vd, adv_tf, omega, omega_s, force, ta, tb;
    Buffer fm, pr, pz, pp, pq, phi, z0, rr, zt, part, part_pq, mpart, scal, lx, lr, ld, lo, levels, pp2;
    Buffer pred[NVFX_MAX_PRED + 1];
    int npred = 0;                     // pred[1..npred] exist
    Buffer params, upload, readback, solid_staging;
    uint64_t solid_staging_fence = 0;
    ComPtr<ID3D12QueryHeap> qheap;

    std::vector<Level> lv;
    int block_level = 0;
    bool fast = true;
    // performance options (env, read at create): NVFX_SIM_FUSED=0 records the reference kernel sequence,
    // NVFX_SIM_BLOCK_M=2|4|8 = finest level handled by the single-group coarse kernel (fused path only)
    bool fused = true;
    int block_m = 8;

    int cur = 0;
    uint64_t counter = 0;      // submissions that used a ring slot
    uint64_t step_no = 0;      // Solver3D meta.step

    // ---- helpers
    D3D12_CPU_DESCRIPTOR_HANDLE cpu(int slot) const {
        D3D12_CPU_DESCRIPTOR_HANDLE h = heap->GetCPUDescriptorHandleForHeapStart();
        h.ptr += static_cast<SIZE_T>(slot) * inc;
        return h;
    }
    bool init();
    // internal profiling (env NVFX_SIM_PROFILE=1): a timestamp after every dispatch of a step, the step
    // waits for the GPU, per-kernel statistics are printed to stderr by nvfx_solver_destroy
    struct Prof {
        bool on = false;
        ComPtr<ID3D12QueryHeap> heap;
        Buffer rb;
        std::vector<std::string> labels;
        std::map<std::string, std::vector<double>> us;
        int steps = 0;
    } prof;
    bool ensure_preds(int k);
    bool wait_slot(uint64_t c);
    void fill_params(Params& p, const NvfxForces* f, float dt) const;
};

