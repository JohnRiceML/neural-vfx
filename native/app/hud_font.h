// out: 64 glyphs x 2 uint32 (x = rows 0-3, y = rows 4-6), byte r of a word = row bits, bit 4 = leftmost column
inline void hud_font_pack(uint32_t out[64][2]) {
    for (int g = 0; g < 64; ++g) {
        out[g][0] = out[g][1] = 0;
        for (int r = 0; r < 7; ++r) {
            uint32_t bits = 0;
            for (int c = 0; c < 5; ++c)
                if (kHudFont5x7[g][r][c] == '#') bits |= 1u << (4 - c);
            out[g][r / 4] |= bits << ((r % 4) * 8);
        }
    }
}
