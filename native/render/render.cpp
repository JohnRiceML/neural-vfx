void fill_params(const NvfxRenderer* r, RParams& P, const NvfxCamera& cam, const NvfxCamera* prev, bool aux,
                 bool has_solid, bool has_vel, uint32_t slot) {
    std::memset(&P, 0, sizeof P);
    const NvfxRenderParams& p = r->p;
    P.k_abs = p.k_abs; P.k_shadow = p.k_shadow; P.k_solid = p.k_solid; P.k_amb = p.k_amb;
    P.k_emit = p.k_emit; P.emit_min = p.emit_min; P.emit_scale = p.emit_scale; P.soot = p.soot;
    P.fire_light = p.fire_light; P.phase_g = p.phase_g; P.exposure = p.exposure; P.bloom = p.bloom;
    P.bloom_thresh = p.bloom_thresh; P.t_lo = p.t_lo; P.t_hi = p.t_hi; P.d_eps = p.d_eps;
    P.floor_op = p.floor_opacity; P.ms_a = p.ms_a; P.ms_b = p.ms_b; P.ms_c = p.ms_c;
    P.rim = p.rim; P.contrast = p.contrast; P.steps = p.steps; P.glow_coarse = p.glow_coarse;
    double L0 = p.light_dir[0], L1 = p.light_dir[1], L2 = p.light_dir[2];
    double ln = std::sqrt(L0 * L0 + L1 * L1 + L2 * L2);
    P.light_dir[0] = float(L0 / ln); P.light_dir[1] = float(L1 / ln); P.light_dir[2] = float(L2 / ln);
    auto c3 = [](float* d, const float* s) { d[0] = s[0]; d[1] = s[1]; d[2] = s[2]; d[3] = 0.0f; };
    c3(P.key_col, p.key_col); c3(P.amb_col, p.amb_col); c3(P.smoke_albedo, p.smoke_albedo); c3(P.bg_top, p.bg_top);
    c3(P.bg_bot, p.bg_bot); c3(P.floor_col, p.floor_col); c3(P.grid_col, p.grid_col); c3(P.obst_col, p.obst_col);
    double asp = double(r->mw) / double(r->mh);   // Python: asp = self.mw / self.mh
    camera_basis(cam, asp, P.cam);
    if (aux && prev) camera_basis(*prev, asp, P.cam_prev);
    else std::memcpy(P.cam_prev, P.cam, sizeof P.cam);
    P.out_w = float(r->ow); P.out_h = float(r->oh); P.sim_dt = NVFX_SIM_DT; P.solid_res = float(r->N);
    P.N = uint32_t(r->N); P.L = uint32_t(r->L); P.mw = uint32_t(r->mw); P.mh = uint32_t(r->mh);
    P.ow = uint32_t(r->ow); P.oh = uint32_t(r->oh); P.bw = uint32_t(r->bw); P.bh = uint32_t(r->bh);
    P.bw2 = uint32_t(r->bw2); P.bh2 = uint32_t(r->bh2);
    P.has_solid = has_solid ? 1u : 0u; P.has_vel = has_vel ? 1u : 0u;
    P.in_vd = R_IN0 + 3 * slot; P.in_tf = R_IN0 + 3 * slot + 1; P.in_solid = R_IN0 + 3 * slot + 2;
    P.aux_on = aux ? 1u : 0u;
    P.dither_mode = r->dither_mode;
    gauss1d(1.0, P.gs);
    gauss1d(1.2, P.g3);
    gauss1d(2.0, P.g2);
}

// flat job dispatch: up to three thread ranges, 64-thread groups, 2D grid when > 65535 groups
struct Rec {
    NvfxRenderer* r;
    ID3D12GraphicsCommandList2* l;
    std::vector<D3D12_RESOURCE_BARRIER> pending;
    ID3D12PipelineState* bound = nullptr;

    void use(Pso p) {
        ID3D12PipelineState* ps = r->pso[p].Get();
        if (ps != bound) { l->SetPipelineState(ps); bound = ps; }
    }
    void flat(Pso p, uint32_t n0, uint32_t n1 = 0, uint32_t n2 = 0) {
        uint64_t total = uint64_t(n0) + n1 + n2;
        if (total == 0) return;
        uint32_t groups = cdiv(total, 64);
        uint32_t gx = std::min<uint32_t>(groups, kMaxGroups), gy = cdiv(groups, gx);
        uint32_t k[8] = {n0, n1, n2, 0, 0, 0, 0, gx * 64u};
        l->SetComputeRoot32BitConstants(0, 8, k, 0);
        use(p);
        l->Dispatch(gx, gy, 1);
    }
    void grid(Pso p, uint32_t gx, uint32_t gy, uint32_t k0 = 0) {
        uint32_t k[8] = {k0, 0, 0, 0, 0, 0, 0, 0};
        l->SetComputeRoot32BitConstants(0, 8, k, 0);
        use(p);
        l->Dispatch(gx, gy, 1);
    }
    void tr(ID3D12Resource* res, D3D12_RESOURCE_STATES a, D3D12_RESOURCE_STATES b) { pending.push_back(transition(res, a, b)); }
    void sync(bool with_uav = true) {
        if (with_uav) pending.push_back(uav_barrier());
        if (!pending.empty()) l->ResourceBarrier(static_cast<UINT>(pending.size()), pending.data());
        pending.clear();
    }
};

NvfxResult record_draw(NvfxRenderer* r, ID3D12GraphicsCommandList2* l, NvfxSolver* solver, const NvfxCamera* cam,
                       const NvfxCamera* prev, int32_t flags) {
    if (!solver || !valid_camera(cam) || (prev && !valid_camera(prev))) {
        set_error("invalid solver or camera");
        return NVFX_ERR_INVALID_ARG;
    }
    if (flags & ~(NVFX_RENDER_AUX | NVFX_RENDER_REUSE_VOLUME | NVFX_RENDER_NO_SOLID | NVFX_RENDER_NO_VELOCITY)) {
        set_error("unknown draw flags 0x%x", unsigned(flags));
        return NVFX_ERR_INVALID_ARG;
    }
    auto* vd = static_cast<ID3D12Resource*>(nvfx_solver_texture(solver, NVFX_TEX_VEL_DENSITY));
    auto* tf = static_cast<ID3D12Resource*>(nvfx_solver_texture(solver, NVFX_TEX_TEMP_FUEL));
    auto* so = static_cast<ID3D12Resource*>(nvfx_solver_texture(solver, NVFX_TEX_SOLID));
    int n = nvfx_solver_res(solver);
    if (!vd || !tf || !so || n <= 0) { set_error("solver textures unavailable"); return NVFX_ERR_INVALID_ARG; }
    {
        D3D12_RESOURCE_DESC a = vd->GetDesc(), b = tf->GetDesc(), c = so->GetDesc();
        if (a.Format != DXGI_FORMAT_R32G32B32A32_FLOAT || b.Format != DXGI_FORMAT_R32G32_FLOAT || c.Format != DXGI_FORMAT_R32_FLOAT ||
            a.Dimension != D3D12_RESOURCE_DIMENSION_TEXTURE3D || a.Width != UINT64(n) || a.Height != UINT(n) || a.DepthOrArraySize != n) {
            set_error("solver textures do not match the nvfx.h contract");
            return NVFX_ERR_INTERNAL;
        }
    }
    if (!r->ensure_volume(n)) return NVFX_ERR_DEVICE;

    const bool aux = (flags & NVFX_RENDER_AUX) != 0;
    const bool has_solid = (flags & NVFX_RENDER_NO_SOLID) == 0;
    const bool has_vel = (flags & NVFX_RENDER_NO_VELOCITY) == 0;
    const bool reuse = (flags & NVFX_RENDER_REUSE_VOLUME) && r->have_vol && r->vol_nosolid == !has_solid;
    int32_t ran = flags & ~NVFX_RENDER_REUSE_VOLUME;
    if (reuse) ran |= NVFX_RENDER_REUSE_VOLUME;

    uint64_t c = r->counter + 1;
    if (!r->wait_slot(c)) return NVFX_ERR_DEVICE;
    r->counter = c;
    const uint32_t slot = uint32_t((c - 1) % kRing), qs = uint32_t((c - 1) % kRb);

    // inputs of this draw: SRVs of the solver's current textures into this ring slot's descriptors
    r->srv_tex3d(vd, DXGI_FORMAT_R32G32B32A32_FLOAT, R_IN0 + 3 * slot);
    r->srv_tex3d(tf, DXGI_FORMAT_R32G32_FLOAT, R_IN0 + 3 * slot + 1);
    r->srv_tex3d(so, DXGI_FORMAT_R32_FLOAT, R_IN0 + 3 * slot + 2);
    auto* P = reinterpret_cast<RParams*>(static_cast<uint8_t*>(r->upload.map) + uint64_t(slot) * kSlotBytes);
    fill_params(r, *P, *cam, prev, aux, has_solid, has_vel, slot);

    Rec q{r, l};
    ID3D12DescriptorHeap* h = r->heap.Get();
    l->SetDescriptorHeaps(1, &h);
    l->SetComputeRootSignature(r->rs.Get());
    l->SetComputeRootConstantBufferView(1, r->upload.va() + uint64_t(slot) * kSlotBytes);
    l->EndQuery(r->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * kTs + 0);

    // outputs to UAV; a leading UAV barrier orders us after a previous draw recorded into the same list
    ID3D12Resource* outs[4] = {r->color.Get(), r->alpha.Get(), r->depth.Get(), r->motion.Get()};
    for (ID3D12Resource* o : outs) q.tr(o, NPSR, UAV);
    const uint32_t n3 = uint32_t(n) * n * n, L3 = uint32_t(r->L) * r->L * r->L;
    const uint32_t B3 = R_BRICKS * R_BRICKS * R_BRICKS, G3 = R_GLOW * R_GLOW * R_GLOW, C3 = R_GLOW_C * R_GLOW_C * R_GLOW_C;
    if (!reuse) {
        // ---- volume prep (renderer.py: pack + _upload_solid + _prep)
        q.tr(r->vol16.Get(), NPSR, UAV);
        q.tr(r->vel16.Get(), NPSR, UAV);
        q.tr(r->light.Get(), NPSR, UAV);
        q.tr(r->glow.Get(), NPSR, UAV);
        if (has_solid) q.tr(r->solid8.Get(), NPSR, UAV);
        q.sync();
        q.flat(PREP1, n3, B3);
        q.tr(r->vol16.Get(), UAV, NPSR);
        q.tr(r->vel16.Get(), UAV, NPSR);
        q.sync();
        q.flat(PREP2, n3, G3);
        q.sync();
        q.flat(PREP3, has_solid ? n3 : 0u, G3, C3);
        if (has_solid) q.tr(r->solid8.Get(), UAV, NPSR);
        q.sync();
        q.flat(PREP4, L3, G3, C3);
        q.tr(r->light.Get(), UAV, NPSR);
        q.sync();
        q.flat(PREP5, G3, C3);
        q.sync();
        q.flat(PREP6, G3);
        q.tr(r->glow.Get(), UAV, NPSR);
        q.sync();
        r->have_vol = true;
        r->vol_nosolid = !has_solid;
    } else {
        q.sync();
    }
    l->EndQuery(r->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * kTs + 1);

    // ---- view: march (+ aux sums)
    const bool aux_pso = aux || r->single_march;
    q.grid(aux_pso ? MARCH_AUX : MARCH, cdiv(r->mw, 8), cdiv(r->mh, 8), aux ? 0u : 1u);
    q.sync();
    l->EndQuery(r->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * kTs + 2);
    // bloom + composite (+ aux resolve)
    q.grid(BLOOM1, cdiv(r->bw, 16), cdiv(r->bh, 16));
    q.sync();
    q.flat(BLOOM2, uint32_t(r->bw2) * r->bh2);
    q.sync();
    q.grid(BLOOM3, cdiv(r->bw, 8), cdiv(r->bh, 8));
    q.sync();
    q.grid(r->dbl ? COMPOSITE_D : COMPOSITE_F, cdiv(r->ow, 8), cdiv(r->oh, 8));
    for (ID3D12Resource* o : outs) q.tr(o, UAV, NPSR);
    q.sync();
    l->EndQuery(r->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * kTs + 3);

    // timestamps + tag into the readback ring (read by get_timings / wait_slot, never blocking)
    D3D12_GPU_VIRTUAL_ADDRESS base = r->readback.va() + uint64_t(qs) * sizeof(RbSlot);
    l->ResolveQueryData(r->qheap.Get(), D3D12_QUERY_TYPE_TIMESTAMP, qs * kTs, kTs, r->readback.res.Get(),
                        uint64_t(qs) * sizeof(RbSlot));
    D3D12_WRITEBUFFERIMMEDIATE_PARAMETER wp[4] = {
        {base + 32, uint32_t(ran)}, {base + 40, uint32_t(c)}, {base + 44, uint32_t(c >> 32)}, {base + 36, uint32_t(c)}};
    D3D12_WRITEBUFFERIMMEDIATE_MODE wm[4] = {D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT, D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT,
                                             D3D12_WRITEBUFFERIMMEDIATE_MODE_DEFAULT, D3D12_WRITEBUFFERIMMEDIATE_MODE_MARKER_OUT};
    l->WriteBufferImmediate(4, wp, wm);
    return NVFX_OK;
}

bool check_params(const NvfxRenderParams* p) {
    if (!(p->steps > 0.0f) || p->steps > 1.0e5f) { set_error("steps must be > 0"); return false; }
    if (p->light_res < 2 || p->light_res > 512) { set_error("light_res must be 2..512"); return false; }
    if (!(p->t_hi > p->t_lo)) { set_error("t_hi must be > t_lo"); return false; }
    double ln = std::sqrt(double(p->light_dir[0]) * p->light_dir[0] + double(p->light_dir[1]) * p->light_dir[1] +
                          double(p->light_dir[2]) * p->light_dir[2]);
    if (!(ln > 0.0) || !std::isfinite(ln)) { set_error("light_dir must be non-zero"); return false; }
    return true;
}

D3D12_RESOURCE_DESC tex_desc(NvfxRenderer* r, NvfxRenderTexture which, int& bpp) {
    ID3D12Resource* t = which == NVFX_RENDER_TEX_COLOR ? r->color.Get()
                        : which == NVFX_RENDER_TEX_ALPHA ? r->alpha.Get()
                        : which == NVFX_RENDER_TEX_DEPTH ? r->depth.Get() : r->motion.Get();
    bpp = which == NVFX_RENDER_TEX_COLOR || which == NVFX_RENDER_TEX_MOTION ? 4 : 2;
    return t->GetDesc();
}

