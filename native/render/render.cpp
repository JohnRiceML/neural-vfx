// Native port of vfx/render3d VolumeRenderer (D3D12 compute, HLSL). Same pipeline stages and constants.
// OWNER: native render engineer. API: nvfx_render.h (proposed for include/nvfx.h).
//
// Recording model (as native/sim): one command list per draw, one shader-visible descriptor heap bound once,
// one root signature (8 root constants + one root CBV + a static trilinear/clamp sampler), every resource reached
// through ResourceDescriptorHeap[R_*]. Global UAV barriers only between dependent dispatches, state transitions
// batched into them. The per-draw parameter block lives in a 16-slot upload ring read directly as the root CBV;
// the solver's (ping-ponging) textures get their SRVs written into the same ring slot of the heap. Timestamps go
// to a readback ring tagged with a WriteBufferImmediate marker, read without blocking.
