struct NvfxRenderer {
    NvfxContext* ctx = nullptr;
    int ow = 0, oh = 0, mw = 0, mh = 0, bw = 0, bh = 0, bw2 = 0, bh2 = 0;
    float scale = 0.5f;
    NvfxRenderParams p = {};
    bool dbl = true;            // device runs double-precision shader ops (composite dither)
    bool single_march = false;  // env NVFX_RENDER_SINGLE_MARCH=1: colour-only draws also use the aux march PSO
    uint32_t dither_mode = 0;   // env NVFX_RENDER_DITHER_MODE (see post.hlsl)

    ComPtr<ID3D12RootSignature> rs;
    ComPtr<ID3D12PipelineState> pso[PSO_COUNT];
    ComPtr<ID3D12DescriptorHeap> heap;
    UINT inc = 0;

    int N = 0;                                   // volume resolution of the volume-sized resources
    ComPtr<ID3D12Resource> vol16, vel16, solid8;
    Buffer s1, s2;
    int L = 0;
    ComPtr<ID3D12Resource> light, glow;
    Buffer occd, occs, g[4], hb[3];
    Buffer hdr, auxhdr, b1, pp, u2, bloom, lut;
    ComPtr<ID3D12Resource> color, alpha, depth, motion;
    Buffer upload, readback;
    ComPtr<ID3D12QueryHeap> qheap;

    uint64_t counter = 0;        // draws recorded
    bool have_vol = false;       // a full draw prepared the volume-only resources
    bool vol_nosolid = false;    // ... with NVFX_RENDER_NO_SOLID

    D3D12_CPU_DESCRIPTOR_HANDLE cpu(int slot) const {
        D3D12_CPU_DESCRIPTOR_HANDLE h = heap->GetCPUDescriptorHandleForHeapStart();
        h.ptr += static_cast<SIZE_T>(slot) * inc;
        return h;
    }
    bool init();
    bool ensure_volume(int n);
    bool make_light(int n);
    bool upload_lut();
    bool wait_slot(uint64_t c);
    void srv_tex3d(ID3D12Resource* r, DXGI_FORMAT f, int slot);
    void uav_tex3d(ID3D12Resource* r, DXGI_FORMAT f, int slot, int depth);
    bool sbuf(Buffer& b, uint64_t count, uint32_t stride, int slot, const char* name);
    bool tex2d(ComPtr<ID3D12Resource>& t, DXGI_FORMAT f, int slot, const char* name);
};

void NvfxRenderer::srv_tex3d(ID3D12Resource* r, DXGI_FORMAT f, int slot) {
    D3D12_SHADER_RESOURCE_VIEW_DESC d = {};
    d.Format = f;
    d.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE3D;
    d.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
    d.Texture3D.MipLevels = 1;
    ctx->device->CreateShaderResourceView(r, &d, cpu(slot));
}

void NvfxRenderer::uav_tex3d(ID3D12Resource* r, DXGI_FORMAT f, int slot, int dep) {
    D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
    d.Format = f;
    d.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE3D;
    d.Texture3D.WSize = UINT(dep);
    ctx->device->CreateUnorderedAccessView(r, nullptr, &d, cpu(slot));
}

bool NvfxRenderer::sbuf(Buffer& b, uint64_t count, uint32_t stride, int slot, const char* name) {
    if (!ctx->create_buffer(b, count * stride, D3D12_HEAP_TYPE_DEFAULT, true, name)) return false;
    D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
    d.Format = DXGI_FORMAT_UNKNOWN;
    d.ViewDimension = D3D12_UAV_DIMENSION_BUFFER;
    d.Buffer.NumElements = UINT(count);
    d.Buffer.StructureByteStride = stride;
    ctx->device->CreateUnorderedAccessView(b.res.Get(), nullptr, &d, cpu(slot));
    return true;
}

bool NvfxRenderer::tex2d(ComPtr<ID3D12Resource>& t, DXGI_FORMAT f, int slot, const char* name) {
    D3D12_HEAP_PROPERTIES hp = {D3D12_HEAP_TYPE_DEFAULT};
    D3D12_RESOURCE_DESC rd = {};
    rd.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE2D;
    rd.Width = UINT64(ow);
    rd.Height = UINT(oh);
    rd.DepthOrArraySize = 1;
    rd.MipLevels = 1;
    rd.Format = f;
    rd.SampleDesc.Count = 1;
    rd.Layout = D3D12_TEXTURE_LAYOUT_UNKNOWN;
    rd.Flags = D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS;
    HRESULT hr = ctx->device->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &rd, NPSR, nullptr, IID_PPV_ARGS(&t));
    if (hr == E_OUTOFMEMORY) { set_error("out of memory creating %s", name); return false; }
    if (!ok(hr, name)) return false;
    wchar_t w[128];
    swprintf(w, 128, L"nvfx.render.%hs", name);
    t->SetName(w);
    D3D12_UNORDERED_ACCESS_VIEW_DESC d = {};
    d.Format = f;
    d.ViewDimension = D3D12_UAV_DIMENSION_TEXTURE2D;
    ctx->device->CreateUnorderedAccessView(t.Get(), nullptr, &d, cpu(slot));
    return true;
}

bool NvfxRenderer::wait_slot(uint64_t c) {
    if (c <= uint64_t(kRing)) return true;
    uint64_t prev = c - kRing;
    auto* rb = reinterpret_cast<volatile RbSlot*>(static_cast<uint8_t*>(readback.map) + ((prev - 1) % kRb) * sizeof(RbSlot));
    if (rb->tag == uint32_t(prev)) return true;
    if (!ctx->hosted) {
        if (!ctx->wait(ctx->fence_next - 1)) return false;   // our own submissions: the fence covers it
        if (rb->tag == uint32_t(prev)) return true;
    }
    for (int i = 0; i < 20000; ++i) {   // hosted: the host executes our lists; poll the marker
        Sleep(1);
        if (rb->tag == uint32_t(prev)) return true;
    }
    set_error("draw %llu never completed (host did not execute the recorded list?)", static_cast<unsigned long long>(prev));
    return false;
}

// volume-resolution resources: half-float volume, velocity, blurred solid, solid blur scratch
bool NvfxRenderer::ensure_volume(int n) {
    if (n == N) return true;
    if (N != 0 && !ctx->wait_idle()) return false;   // resolution change: the old resources may be in use
    have_vol = false;
    vol16.Reset(); vel16.Reset(); solid8.Reset(); s1 = Buffer(); s2 = Buffer();
    N = 0;
    if (!ctx->create_tex3d(vol16, DXGI_FORMAT_R16G16_FLOAT, n, NPSR, "render.vol16")) return false;
    if (!ctx->create_tex3d(vel16, DXGI_FORMAT_R16G16B16A16_FLOAT, n, NPSR, "render.vel16")) return false;
    if (!ctx->create_tex3d(solid8, DXGI_FORMAT_R8_UNORM, n, NPSR, "render.solid8")) return false;
    srv_tex3d(vol16.Get(), DXGI_FORMAT_R16G16_FLOAT, R_VOL_SRV);
    uav_tex3d(vol16.Get(), DXGI_FORMAT_R16G16_FLOAT, R_VOL_UAV, n);
    srv_tex3d(vel16.Get(), DXGI_FORMAT_R16G16B16A16_FLOAT, R_VEL_SRV);
    uav_tex3d(vel16.Get(), DXGI_FORMAT_R16G16B16A16_FLOAT, R_VEL_UAV, n);
    srv_tex3d(solid8.Get(), DXGI_FORMAT_R8_UNORM, R_SOLID8_SRV);
    uav_tex3d(solid8.Get(), DXGI_FORMAT_R8_UNORM, R_SOLID8_UAV, n);
    uint64_t n3 = uint64_t(n) * n * n;
    if (!sbuf(s1, n3, 4, R_S1, "render.s1") || !sbuf(s2, n3, 4, R_S2, "render.s2")) return false;
    N = n;
    return true;
}

bool NvfxRenderer::make_light(int n) {
    if (n == L && light) return true;
    if (light && !ctx->wait_idle()) return false;
    have_vol = false;
    light.Reset();
    L = 0;
    if (!ctx->create_tex3d(light, DXGI_FORMAT_R16G16_FLOAT, n, NPSR, "render.light")) return false;
    srv_tex3d(light.Get(), DXGI_FORMAT_R16G16_FLOAT, R_LIGHT_SRV);
    uav_tex3d(light.Get(), DXGI_FORMAT_R16G16_FLOAT, R_LIGHT_UAV, n);
    L = n;
    return true;
}

// blackbody LUT -> default-heap buffer; synchronizes (create, and set_params when t_lo / t_hi / t_ref change)
bool NvfxRenderer::upload_lut() {
    Buffer up;
    if (!ctx->create_buffer(up, R_LUT_N * 16, D3D12_HEAP_TYPE_UPLOAD, false, "render.lut_up")) return false;
    blackbody_lut(p.t_lo, p.t_hi, R_LUT_N, p.t_ref, static_cast<float*>(up.map));
    if (!ctx->wait_idle()) return false;   // draws in flight read the LUT
    ID3D12GraphicsCommandList2* l = ctx->begin();
    if (!l) return false;
    l->CopyBufferRegion(lut.res.Get(), 0, up.res.Get(), 0, R_LUT_N * 16);
    uint64_t v = ctx->submit();
    return v && ctx->wait(v);
}

bool NvfxRenderer::init() {
    ID3D12Device* dev = ctx->device.Get();
    D3D12_FEATURE_DATA_D3D12_OPTIONS o = {};
    dev->CheckFeatureSupport(D3D12_FEATURE_D3D12_OPTIONS, &o, sizeof o);
    dbl = o.DoublePrecisionFloatShaderOps != 0;
    single_march = env_int("NVFX_RENDER_SINGLE_MARCH", 0) != 0;
    dither_mode = static_cast<uint32_t>(std::clamp(env_int("NVFX_RENDER_DITHER_MODE", 0), 0, 2));
    // trilinear filtering of the half-float / unorm textures we sample (always required on FL 11+; checked anyway)
    const DXGI_FORMAT sampled[] = {DXGI_FORMAT_R16G16_FLOAT, DXGI_FORMAT_R16G16B16A16_FLOAT, DXGI_FORMAT_R8_UNORM};
    for (DXGI_FORMAT f : sampled) {
        D3D12_FEATURE_DATA_FORMAT_SUPPORT fs = {f};
        if (FAILED(dev->CheckFeatureSupport(D3D12_FEATURE_FORMAT_SUPPORT, &fs, sizeof fs)) ||
            !(fs.Support1 & D3D12_FORMAT_SUPPORT1_SHADER_SAMPLE) || !(fs.Support1 & D3D12_FORMAT_SUPPORT1_TEXTURE3D) ||
            !(fs.Support2 & D3D12_FORMAT_SUPPORT2_UAV_TYPED_STORE)) {
            set_error("device lacks 3D sampling / typed UAV store for DXGI format %d", int(f));
            return false;
        }
    }

    // root signature: b0 = 8 constants, b1 = root CBV, s0 = trilinear clamp sampler, heap directly indexed
    D3D12_ROOT_PARAMETER1 rp[2] = {};
    rp[0].ParameterType = D3D12_ROOT_PARAMETER_TYPE_32BIT_CONSTANTS;
    rp[0].Constants = {0, 0, 8};
    rp[0].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    rp[1].ParameterType = D3D12_ROOT_PARAMETER_TYPE_CBV;
    rp[1].Descriptor = {1, 0, D3D12_ROOT_DESCRIPTOR_FLAG_DATA_STATIC_WHILE_SET_AT_EXECUTE};
    rp[1].ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    D3D12_STATIC_SAMPLER_DESC ss = {};
    ss.Filter = D3D12_FILTER_MIN_MAG_MIP_LINEAR;
    ss.AddressU = ss.AddressV = ss.AddressW = D3D12_TEXTURE_ADDRESS_MODE_CLAMP;
    ss.MaxAnisotropy = 1;
    ss.ComparisonFunc = D3D12_COMPARISON_FUNC_NEVER;
    ss.MinLOD = 0.0f;
    ss.MaxLOD = 0.0f;
    ss.ShaderRegister = 0;
    ss.ShaderVisibility = D3D12_SHADER_VISIBILITY_ALL;
    D3D12_VERSIONED_ROOT_SIGNATURE_DESC rsd = {};
    rsd.Version = D3D_ROOT_SIGNATURE_VERSION_1_1;
    rsd.Desc_1_1.NumParameters = 2;
    rsd.Desc_1_1.pParameters = rp;
    rsd.Desc_1_1.NumStaticSamplers = 1;
    rsd.Desc_1_1.pStaticSamplers = &ss;
    rsd.Desc_1_1.Flags = D3D12_ROOT_SIGNATURE_FLAG_CBV_SRV_UAV_HEAP_DIRECTLY_INDEXED;
    ComPtr<ID3DBlob> blob, err;
    if (FAILED(D3D12SerializeVersionedRootSignature(&rsd, &blob, &err))) {
        set_error("render root signature: %s", err ? static_cast<const char*>(err->GetBufferPointer()) : "?");
        return false;
    }
    if (!ok(dev->CreateRootSignature(0, blob->GetBufferPointer(), blob->GetBufferSize(), IID_PPV_ARGS(&rs)),
            "CreateRootSignature(render)"))
        return false;
    for (int i = 0; i < PSO_COUNT; ++i) {
        if (i == COMPOSITE_D && !dbl) continue;   // device without doubles: float-only composite
        const RenderShader* e = nullptr;
        for (const auto& t : kRenderShaders)
            if (std::strcmp(t.name, kPsoNames[i]) == 0) e = &t;
        if (!e) { set_error("internal: render shader %s not embedded", kPsoNames[i]); return false; }
        D3D12_COMPUTE_PIPELINE_STATE_DESC d = {};
        d.pRootSignature = rs.Get();
        d.CS = {e->data, e->size};
        if (!ok(dev->CreateComputePipelineState(&d, IID_PPV_ARGS(&pso[i])), kPsoNames[i])) return false;
    }

    D3D12_DESCRIPTOR_HEAP_DESC hd = {D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV, R_COUNT, D3D12_DESCRIPTOR_HEAP_FLAG_SHADER_VISIBLE};
    if (!ok(dev->CreateDescriptorHeap(&hd, IID_PPV_ARGS(&heap)), "CreateDescriptorHeap(render)")) return false;
    inc = dev->GetDescriptorHandleIncrementSize(D3D12_DESCRIPTOR_HEAP_TYPE_CBV_SRV_UAV);

    // fixed-size volume-prep resources
    const uint64_t B3 = uint64_t(R_BRICKS) * R_BRICKS * R_BRICKS, G3 = uint64_t(R_GLOW) * R_GLOW * R_GLOW,
                   C3 = uint64_t(R_GLOW_C) * R_GLOW_C * R_GLOW_C;
    if (!sbuf(occd, B3, 4, R_OCCD, "render.occ") || !sbuf(occs, B3, 4, R_OCCS, "render.occ_solid")) return false;
    const int gslot[4] = {R_G0, R_G1, R_G2, R_G3};
    for (int i = 0; i < 4; ++i)
        if (!sbuf(g[i], G3, 16, gslot[i], "render.glow_pyr")) return false;
    const int hslot[3] = {R_H0, R_H1, R_H2};
    for (int i = 0; i < 3; ++i)
        if (!sbuf(hb[i], C3, 16, hslot[i], "render.glow_coarse")) return false;
    if (!ctx->create_tex3d(glow, DXGI_FORMAT_R16G16B16A16_FLOAT, R_GLOW, NPSR, "render.glow")) return false;
    srv_tex3d(glow.Get(), DXGI_FORMAT_R16G16B16A16_FLOAT, R_GLOW_SRV);
    uav_tex3d(glow.Get(), DXGI_FORMAT_R16G16B16A16_FLOAT, R_GLOW_UAV, R_GLOW);
    if (!make_light(p.light_res)) return false;

    // view-size resources
    if (!sbuf(hdr, uint64_t(mw) * mh, 16, R_HDR, "render.hdr") || !sbuf(auxhdr, uint64_t(mw) * mh, 16, R_AUXHDR, "render.aux_hdr") ||
        !sbuf(b1, uint64_t(bw) * bh, 16, R_B1, "render.bloom1") || !sbuf(bloom, uint64_t(bw) * bh, 16, R_BLOOM, "render.bloom") ||
        !sbuf(pp, uint64_t(bw2) * bh2, 16, R_P, "render.bloom2_pool") || !sbuf(u2, uint64_t(bw2) * bh2, 16, R_U2, "render.bloom2_x"))
        return false;
    if (!tex2d(color, DXGI_FORMAT_R8G8B8A8_UNORM, R_COLOR_UAV, "color") || !tex2d(alpha, DXGI_FORMAT_R16_FLOAT, R_ALPHA_UAV, "alpha") ||
        !tex2d(depth, DXGI_FORMAT_R16_FLOAT, R_DEPTH_UAV, "depth") || !tex2d(motion, DXGI_FORMAT_R16G16_FLOAT, R_MOTION_UAV, "motion"))
        return false;

    // LUT (read-only structured buffer)
    if (!ctx->create_buffer(lut, R_LUT_N * 16, D3D12_HEAP_TYPE_DEFAULT, false, "render.lut")) return false;
    {
        D3D12_SHADER_RESOURCE_VIEW_DESC d = {};
        d.Format = DXGI_FORMAT_UNKNOWN;
        d.ViewDimension = D3D12_SRV_DIMENSION_BUFFER;
        d.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING;
        d.Buffer.NumElements = R_LUT_N;
        d.Buffer.StructureByteStride = 16;
        dev->CreateShaderResourceView(lut.res.Get(), &d, cpu(R_LUT));
    }
    if (!ctx->create_buffer(upload, uint64_t(kRing) * kSlotBytes, D3D12_HEAP_TYPE_UPLOAD, false, "render.param_ring")) return false;
    if (!ctx->create_buffer(readback, uint64_t(kRb) * sizeof(RbSlot), D3D12_HEAP_TYPE_READBACK, false, "render.readback"))
        return false;
    std::memset(readback.map, 0, size_t(kRb) * sizeof(RbSlot));
    D3D12_QUERY_HEAP_DESC qd = {D3D12_QUERY_HEAP_TYPE_TIMESTAMP, kRb * kTs, 0};
    if (!ok(dev->CreateQueryHeap(&qd, IID_PPV_ARGS(&qheap)), "CreateQueryHeap(render)")) return false;
    return upload_lut();
}

