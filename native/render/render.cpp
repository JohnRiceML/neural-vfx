// renderer.camera_basis(): 16 floats pos, forward, right, up, tan(fov/2), aspect, 0, 0 (computed in float64)
void camera_basis(const NvfxCamera& cam, double aspect, float out[16]) {
    double pos[3] = {cam.position[0], cam.position[1], cam.position[2]};
    double fw[3] = {cam.target[0] - pos[0], cam.target[1] - pos[1], cam.target[2] - pos[2]};
    double n = std::sqrt(fw[0] * fw[0] + fw[1] * fw[1] + fw[2] * fw[2]) + 1e-12;
    for (double& v : fw) v /= n;
    double u0[3] = {cam.up[0], cam.up[1], cam.up[2]};
    double rt[3] = {u0[1] * fw[2] - u0[2] * fw[1], u0[2] * fw[0] - u0[0] * fw[2], u0[0] * fw[1] - u0[1] * fw[0]};
    double rn = std::sqrt(rt[0] * rt[0] + rt[1] * rt[1] + rt[2] * rt[2]);
    if (rn < 1e-6) { rt[0] = 1.0; rt[1] = 0.0; rt[2] = 0.0; rn = 1.0; }
    for (double& v : rt) v /= rn;
    double up[3] = {fw[1] * rt[2] - fw[2] * rt[1], fw[2] * rt[0] - fw[0] * rt[2], fw[0] * rt[1] - fw[1] * rt[0]};
    const double kDegToRad = 3.141592653589793 / 180.0;   // math.radians
    double th = std::tan(double(cam.fov_y_deg) * kDegToRad * 0.5);
    double all[16] = {pos[0], pos[1], pos[2], fw[0], fw[1], fw[2], rt[0], rt[1], rt[2], up[0], up[1], up[2], th, aspect, 0, 0};
    for (int i = 0; i < 16; ++i) out[i] = static_cast<float>(all[i]);
}

// vfx/render/blackbody.py blackbody_lut(t_lo, t_hi, n, t_ref) in float64, stored float32 (xyz, 0)
double bb_g(double lam, double mu, double s1, double s2) {
    double s = lam < mu ? s1 : s2;
    double a = (lam - mu) / s;
    return std::exp(-0.5 * (a * a));
}
void blackbody_lut(double t_lo, double t_hi, int n, double t_ref, float* out4) {
    const double compress = 0.33, onset = 150.0;
    const double M[3][3] = {{3.2406, -1.5372, -0.4986}, {-0.9689, 1.8758, 0.0415}, {0.0557, -0.2040, 1.0570}};
    const int nl = 401;
    std::vector<double> lam(nl), xb(nl * 3);
    for (int i = 0; i < nl; ++i) {
        double l = 380.0 + double(i) * 1.0;   // np.linspace(380, 780, 401): step exactly 1
        lam[i] = l;
        xb[3 * i + 0] = 1.056 * bb_g(l, 599.8, 37.9, 31.0) + 0.362 * bb_g(l, 442.0, 16.0, 26.7) - 0.065 * bb_g(l, 501.1, 20.4, 26.2);
        xb[3 * i + 1] = 0.821 * bb_g(l, 568.8, 46.9, 40.5) + 0.286 * bb_g(l, 530.9, 16.3, 31.1);
        xb[3 * i + 2] = 1.217 * bb_g(l, 437.0, 11.8, 36.0) + 0.681 * bb_g(l, 459.0, 26.0, 13.8);
    }
    std::vector<double> T(n + 1);
    double step = (t_hi - t_lo) / double(n - 1);
    for (int i = 0; i < n; ++i) T[i] = double(i) * step + t_lo;
    T[n - 1] = t_hi;
    T[n] = t_ref;
    const double h = 6.62607015e-34, c = 2.99792458e8, k = 1.380649e-23;
    std::vector<double> XYZ((n + 1) * 3, 0.0);
    for (int t = 0; t <= n; ++t) {
        double sx = 0, sy = 0, sz = 0;
        for (int i = 0; i < nl; ++i) {
            double l = lam[i] * 1e-9;
            double spec = (2 * h * c * c) / (std::pow(l, 5) * std::expm1(h * c / (l * k * T[t])));
            sx += spec * xb[3 * i + 0];
            sy += spec * xb[3 * i + 1];
            sz += spec * xb[3 * i + 2];
        }
        XYZ[3 * t + 0] = sx; XYZ[3 * t + 1] = sy; XYZ[3 * t + 2] = sz;
    }
    double Yref = XYZ[3 * n + 1];
    for (int t = 0; t < n; ++t) {
        double rgb[3];
        for (int j = 0; j < 3; ++j)
            rgb[j] = std::max(0.0, XYZ[3 * t + 0] * M[j][0] + XYZ[3 * t + 1] * M[j][1] + XYZ[3 * t + 2] * M[j][2]);
        double mx = std::max(rgb[0], std::max(rgb[1], rgb[2]));
        double lum = std::pow(XYZ[3 * t + 1] / Yref, compress);
        double s = std::clamp((T[t] - t_lo) / onset, 0.0, 1.0);
        double fade = s * s * (3 - 2 * s);
        for (int j = 0; j < 3; ++j) out4[4 * t + j] = static_cast<float>((mx > 0 ? rgb[j] / mx : 0.0) * (lum * fade));
        out4[4 * t + 3] = 0.0f;
    }
}

// renderer._gauss1d(sigma) in float32 (torch): radius max(1, ceil(2.5 sigma))
int gauss1d(double sigma, float* w) {
    int r = std::max(1, int(std::ceil(2.5 * sigma)));
    float sum = 0.0f;
    for (int i = -r; i <= r; ++i) {
        float t = static_cast<float>(i) / static_cast<float>(sigma);
        float e = std::exp(-0.5f * (t * t));
        w[i + r] = e;
        sum += e;
    }
    for (int i = 0; i < 2 * r + 1; ++i) w[i] /= sum;
    return 2 * r + 1;
}

float half_to_float(uint16_t hv) {
    uint32_t s = uint32_t(hv >> 15) << 31, e = (hv >> 10) & 0x1f, m = hv & 0x3ff, f;
    if (e == 0) {
        if (m == 0) f = s;
        else {   // subnormal
            int sh = 0;
            while (!(m & 0x400)) { m <<= 1; ++sh; }
            m &= 0x3ff;
            f = s | (uint32_t(127 - 15 - sh + 1) << 23) | (m << 13);
        }
    } else if (e == 31) f = s | 0x7f800000u | (m << 13);
    else f = s | ((e - 15 + 127) << 23) | (m << 13);
    float r;
    std::memcpy(&r, &f, 4);
    return r;
}

bool valid_camera(const NvfxCamera* c) {
    if (!c) return false;
    for (int i = 0; i < 3; ++i)
        if (!std::isfinite(c->position[i]) || !std::isfinite(c->target[i]) || !std::isfinite(c->up[i])) return false;
    return c->fov_y_deg > 0.0f && c->fov_y_deg < 180.0f;
}
